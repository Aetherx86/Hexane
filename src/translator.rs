use crate::ast::*;
use crate::diagnostics::Diagnostic;
use std::collections::HashMap;

pub struct Translator {
    indent: usize,
    buffer: String,
    classes: HashMap<String, ClassDef>,
    functions: HashMap<String, Function>,
    returned_var: Option<String>,
}

impl Translator {
    pub fn new() -> Self {
        Self {
            indent: 0,
            buffer: String::new(),
            classes: HashMap::new(),
            functions: HashMap::new(),
            returned_var: None,
        }
    }

    fn push_indent(&mut self) {
        self.indent += 2;
    }

    fn pop_indent(&mut self) {
        if self.indent >= 2 {
            self.indent -= 2;
        }
    }

    fn write_indent(&mut self) {
        for _ in 0..self.indent {
            self.buffer.push(' ');
        }
    }

    fn writeln(&mut self, s: &str) {
        self.write_indent();
        self.buffer.push_str(s);
        self.buffer.push('\n');
    }

    pub fn translate(&mut self, program: &Program) -> Result<String, Diagnostic> {
        self.buffer.clear();

        for class in &program.classes {
            self.classes.insert(class.name.clone(), class.clone());
        }
        for func in &program.functions {
            self.functions.insert(func.name.clone(), func.clone());
        }
        for class in &program.classes {
            for method in &class.methods {
                let full_name = format!("{}_{}", class.name, method.name);
                self.functions.insert(full_name, method.clone());
            }
        }

        self.writeln("// Generated by Carbonation Toolchain (alias: graphene, hexane, hexene)");
        self.writeln("// Copyright (c) 2026 jk9576. All rights reserved.");
        self.writeln("#include <stdio.h>");
        self.writeln("#include <stdint.h>");
        self.writeln("#include <stdbool.h>");
        self.writeln("#include <stdlib.h>");
        self.writeln("#include <string.h>");
        self.writeln("#include <math.h>");
        self.writeln("");
        self.writeln("#ifdef __cplusplus");
        self.writeln("extern \"C\" {");
        self.writeln("#endif");
        self.writeln("");

        // Forward declare structs
        for class in &program.classes {
            self.writeln(&format!("typedef struct {} {};", class.name, class.name));
        }
        if !program.classes.is_empty() {
            self.writeln("");
        }

        // Struct definitions
        for class in &program.classes {
            self.translate_class_struct(class);
        }

        // Forward declare functions
        for func in &program.functions {
            let sig = self.function_signature(func, &func.name);
            if func.is_extern {
                self.writeln(&format!("extern {};", sig));
            } else {
                self.writeln(&format!("{};", sig));
            }
        }
        for class in &program.classes {
            for method in &class.methods {
                let method_name = format!("{}_{}", class.name, method.name);
                let sig = self.function_signature_method(class, method, &method_name);
                self.writeln(&format!("{};", sig));
            }
        }
        self.writeln("");

        // Globals
        for global in &program.globals {
            self.translate_global(global);
        }
        if !program.globals.is_empty() {
            self.writeln("");
        }

        // Function bodies
        for func in &program.functions {
            if !func.is_extern {
                self.translate_function(func, &func.name)?;
                self.writeln("");
            }
        }

        // Class methods
        for class in &program.classes {
            for method in &class.methods {
                let method_name = format!("{}_{}", class.name, method.name);
                self.translate_method(class, method, &method_name)?;
                self.writeln("");
            }
        }

        // Entry point wrapper
        self.translate_entry_point(program);

        self.writeln("");
        self.writeln("#ifdef __cplusplus");
        self.writeln("}");
        self.writeln("#endif");

        Ok(self.buffer.clone())
    }

    fn translate_class_struct(&mut self, class: &ClassDef) {
        self.writeln(&format!("struct {} {{", class.name));
        self.push_indent();
        for (fname, fty) in &class.fields {
            match fty {
                Type::Array(inner, size) => {
                    let inner_c = self.type_to_c(inner);
                    self.writeln(&format!("{} {}[{}];", inner_c, fname, size));
                }
                _ => {
                    let ty_c = self.type_to_c(fty);
                    self.writeln(&format!("{} {};", ty_c, fname));
                }
            }
        }
        if class.fields.is_empty() {
            self.writeln("char _dummy;");
        }
        self.pop_indent();
        self.writeln("};\n");
    }

    fn type_to_c(&self, ty: &Type) -> String {
        match ty {
            Type::I8 => "int8_t".to_string(),
            Type::I16 => "int16_t".to_string(),
            Type::I32 => "int32_t".to_string(),
            Type::I64 => "int64_t".to_string(),
            Type::U8 => "uint8_t".to_string(),
            Type::U16 => "uint16_t".to_string(),
            Type::U32 => "uint32_t".to_string(),
            Type::U64 => "uint64_t".to_string(),
            Type::Int => "int32_t".to_string(),
            Type::F32 => "float".to_string(),
            Type::F64 => "double".to_string(),
            Type::Bool => "bool".to_string(),
            Type::String => "const char*".to_string(),
            Type::Void => "void".to_string(),
            Type::Auto => "auto".to_string(),
            Type::Pointer(inner) => format!("{}*", self.type_to_c(inner)),
            Type::Custom(name) => name.clone(),
            Type::Array(inner, size) => format!("{}[{}]", self.type_to_c(inner), size),
        }
    }

    fn function_signature(&self, func: &Function, name: &str) -> String {
        let ret_c = self.type_to_c(&func.return_type);
        let mut params = Vec::new();
        for param in &func.params {
            let pty = self.type_to_c(&param.ty);
            let pref = if param.is_ref { "*" } else { "" };
            params.push(format!("{}{} {}", pty, pref, param.name));
        }
        let param_str = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };
        format!("{} {}({})", ret_c, name, param_str)
    }

    fn function_signature_method(&self, class: &ClassDef, method: &Function, name: &str) -> String {
        let ret_c = self.type_to_c(&method.return_type);
        let mut params = Vec::new();
        for param in &method.params {
            if param.is_self {
                let ptr = if param.is_ref { "*" } else { "" };
                params.push(format!("{}{} self", class.name, ptr));
            } else {
                let pty = self.type_to_c(&param.ty);
                let pref = if param.is_ref { "*" } else { "" };
                params.push(format!("{}{} {}", pty, pref, param.name));
            }
        }
        let param_str = if params.is_empty() {
            "void".to_string()
        } else {
            params.join(", ")
        };
        format!("{} {}({})", ret_c, name, param_str)
    }

    fn translate_global(&mut self, stmt: &Stmt) {
        if let Stmt::VarDecl { name, ty, init, .. } = stmt {
            let ty_c = ty
                .as_ref()
                .map(|t| self.type_to_c(t))
                .unwrap_or_else(|| "int32_t".to_string());
            if let Some(init_expr) = init {
                let init_c = self.translate_expr(init_expr);
                self.writeln(&format!("{} {} = {};", ty_c, name, init_c));
            } else {
                self.writeln(&format!("{} {} = {0};", ty_c, name));
            }
        }
    }

    fn translate_function(&mut self, func: &Function, name: &str) -> Result<(), Diagnostic> {
        let sig = self.function_signature(func, name);
        self.writeln(&format!("{} {{", sig));
        self.push_indent();

        let old_returned_var = self.returned_var.clone();
        self.returned_var = None;

        for stmt in &func.body {
            self.translate_stmt(stmt)?;
        }

        self.returned_var = old_returned_var;
        self.pop_indent();
        self.writeln("}");
        Ok(())
    }

    fn translate_method(
        &mut self,
        class: &ClassDef,
        method: &Function,
        name: &str,
    ) -> Result<(), Diagnostic> {
        let sig = self.function_signature_method(class, method, name);
        self.writeln(&format!("{} {{", sig));
        self.push_indent();

        let old_returned_var = self.returned_var.clone();
        self.returned_var = None;

        for stmt in &method.body {
            self.translate_stmt(stmt)?;
        }

        self.returned_var = old_returned_var;
        self.pop_indent();
        self.writeln("}");
        Ok(())
    }

    fn translate_stmt(&mut self, stmt: &Stmt) -> Result<(), Diagnostic> {
        match stmt {
            Stmt::VarDecl {
                name,
                ty,
                init,
                is_returned,
                ..
            } => {
                if *is_returned {
                    self.returned_var = Some(name.clone());
                }

                if let Some(Type::Array(inner, size)) = ty {
                    let inner_c = self.type_to_c(inner);
                    if let Some(init_expr) = init {
                        let init_c = self.translate_expr(init_expr);
                        self.writeln(&format!("{} {}[{}] = {};", inner_c, name, size, init_c));
                    } else {
                        self.writeln(&format!("{} {}[{}] = {{0}};", inner_c, name, size));
                    }
                    return Ok(());
                }

                let ty_c = ty
                    .as_ref()
                    .map(|t| self.type_to_c(t))
                    .unwrap_or_else(|| "int32_t".to_string());
                if let Some(init_expr) = init {
                    let init_c = self.translate_expr(init_expr);
                    self.writeln(&format!("{} {} = {};", ty_c, name, init_c));
                } else {
                    self.writeln(&format!("{} {} = ({}){{0}};", ty_c, name, ty_c));
                }
                Ok(())
            }
            Stmt::Expr(expr) => {
                // Check if it's Core.Print or Core.PrintStr
                if self.try_translate_print_stmt(expr) {
                    return Ok(());
                }
                let c_expr = self.translate_expr(expr);
                self.writeln(&format!("{};", c_expr));
                Ok(())
            }
            Stmt::If {
                cond,
                then_branch,
                else_branch,
                ..
            } => {
                let cond_c = self.translate_expr(cond);
                self.writeln(&format!("if ({}) {{", cond_c));
                self.push_indent();
                for s in then_branch {
                    self.translate_stmt(s)?;
                }
                self.pop_indent();

                if let Some(else_stmts) = else_branch {
                    self.writeln("} else {");
                    self.push_indent();
                    for s in else_stmts {
                        self.translate_stmt(s)?;
                    }
                    self.pop_indent();
                }
                self.writeln("}");
                Ok(())
            }
            Stmt::While { cond, body, .. } => {
                let cond_c = self.translate_expr(cond);
                self.writeln(&format!("while ({}) {{", cond_c));
                self.push_indent();
                for s in body {
                    self.translate_stmt(s)?;
                }
                self.pop_indent();
                self.writeln("}");
                Ok(())
            }
            Stmt::For {
                var_name,
                var_ty,
                iterable,
                body,
                ..
            } => {
                let ty_c = var_ty
                    .as_ref()
                    .map(|t| self.type_to_c(t))
                    .unwrap_or_else(|| "int32_t".to_string());
                if let Expr::Range {
                    start,
                    end,
                    inclusive,
                    ..
                } = iterable
                {
                    let start_c = self.translate_expr(start);
                    let end_c = self.translate_expr(end);
                    let cmp = if *inclusive { "<=" } else { "<" };
                    self.writeln(&format!(
                        "for ({} {} = {}; {} {} {}; ++{}) {{",
                        ty_c, var_name, start_c, var_name, cmp, end_c, var_name
                    ));
                    self.push_indent();
                    for s in body {
                        self.translate_stmt(s)?;
                    }
                    self.pop_indent();
                    self.writeln("}");
                    return Ok(());
                }

                // Generic array for-loop
                let iter_c = self.translate_expr(iterable);
                let idx_var = format!("__i_{}", var_name);
                self.writeln(&format!(
                    "for (size_t {} = 0; {} < sizeof({})/sizeof({}[0]); ++{}) {{",
                    idx_var, idx_var, iter_c, iter_c, idx_var
                ));
                self.push_indent();
                self.writeln(&format!("{} {} = {}[{}];", ty_c, var_name, iter_c, idx_var));
                for s in body {
                    self.translate_stmt(s)?;
                }
                self.pop_indent();
                self.writeln("}");
                Ok(())
            }
            Stmt::Return {
                value,
                is_return_var,
                ..
            } => {
                if *is_return_var {
                    if let Some(ref name) = self.returned_var {
                        self.writeln(&format!("return {};", name));
                    } else {
                        self.writeln("return;");
                    }
                    return Ok(());
                }

                if let Some(v) = value {
                    let v_c = self.translate_expr(v);
                    self.writeln(&format!("return {};", v_c));
                } else {
                    self.writeln("return;");
                }
                Ok(())
            }
            Stmt::Break(_) => {
                self.writeln("break;");
                Ok(())
            }
            Stmt::Continue(_) => {
                self.writeln("continue;");
                Ok(())
            }
            Stmt::Block(stmts) => {
                self.writeln("{");
                self.push_indent();
                for s in stmts {
                    self.translate_stmt(s)?;
                }
                self.pop_indent();
                self.writeln("}");
                Ok(())
            }
        }
    }

    fn try_translate_print_stmt(&mut self, expr: &Expr) -> bool {
        if let Expr::Call { callee, args, .. } = expr {
            if let Expr::MemberAccess { object, member, .. } = &**callee
                && let Expr::Ident(obj_name, _) = &**object
                && obj_name == "Core"
            {
                if member == "PrintStr" {
                    let arg_c = if let Some(first) = args.first() {
                        self.translate_expr(first)
                    } else {
                        "\"\"".to_string()
                    };
                    self.writeln(&format!("printf(\"%s\", {});", arg_c));
                    return true;
                } else if member == "Print" {
                    if let Some(first) = args.first() {
                        let arg_c = self.translate_expr(first);
                        self.writeln(&format!("printf(\"%lld\\n\", (long long)({}));", arg_c));
                    } else {
                        self.writeln("printf(\"\\n\");");
                    }
                    return true;
                }
            }

            if let Expr::Ident(func_name, _) = &**callee {
                if func_name == "Print" || func_name == "PrintInt" || func_name == "println" {
                    if let Some(first) = args.first() {
                        let arg_c = self.translate_expr(first);
                        self.writeln(&format!("printf(\"%lld\\n\", (long long)({}));", arg_c));
                    } else {
                        self.writeln("printf(\"\\n\");");
                    }
                    return true;
                } else if func_name == "PrintStr" {
                    let arg_c = if let Some(first) = args.first() {
                        self.translate_expr(first)
                    } else {
                        "\"\"".to_string()
                    };
                    self.writeln(&format!("printf(\"%s\", {});", arg_c));
                    return true;
                }
            }
        }
        false
    }

    pub fn translate_expr(&self, expr: &Expr) -> String {
        match expr {
            Expr::Integer(n, _) => format!("{}", n),
            Expr::Float(f, _) => format!("{}", f),
            Expr::Bool(b, _) => format!("{}", b),
            Expr::StringLit(s, _) => {
                let escaped = s
                    .replace('\\', "\\\\")
                    .replace('\"', "\\\"")
                    .replace('\n', "\\n")
                    .replace('\t', "\\t");
                format!("\"{}\"", escaped)
            }
            Expr::Ident(name, _) => {
                if name == "self" {
                    "(*self)".to_string()
                } else {
                    name.clone()
                }
            }
            Expr::Unary {
                op, expr: inner, ..
            } => {
                let inner_c = self.translate_expr(inner);
                match op {
                    UnaryOp::Neg => format!("(-{})", inner_c),
                    UnaryOp::Not => format!("(!{})", inner_c),
                    UnaryOp::BitNot => format!("(~{})", inner_c),
                    UnaryOp::PreInc => format!("(++{})", inner_c),
                    UnaryOp::PreDec => format!("(--{})", inner_c),
                    UnaryOp::PostInc => format!("({}++)", inner_c),
                    UnaryOp::PostDec => format!("({}--)", inner_c),
                    UnaryOp::AddressOf => format!("(&{})", inner_c),
                    UnaryOp::Deref => format!("(*{})", inner_c),
                }
            }
            Expr::Binary {
                op, left, right, ..
            } => {
                let left_c = self.translate_expr(left);
                let right_c = self.translate_expr(right);
                let op_str = match op {
                    BinaryOp::Add => "+",
                    BinaryOp::Sub => "-",
                    BinaryOp::Mul => "*",
                    BinaryOp::Div => "/",
                    BinaryOp::Rem => "%",
                    BinaryOp::Eq => "==",
                    BinaryOp::NotEq => "!=",
                    BinaryOp::Lt => "<",
                    BinaryOp::LtEq => "<=",
                    BinaryOp::Gt => ">",
                    BinaryOp::GtEq => ">=",
                    BinaryOp::And => "&&",
                    BinaryOp::Or => "||",
                    BinaryOp::BitAnd => "&",
                    BinaryOp::BitOr => "|",
                    BinaryOp::BitXor => "^",
                    BinaryOp::Shl => "<<",
                    BinaryOp::Shr => ">>",
                };
                format!("({} {} {})", left_c, op_str, right_c)
            }
            Expr::Assign {
                target, op, value, ..
            } => {
                let target_c = self.translate_expr(target);
                let value_c = self.translate_expr(value);
                let op_str = match op {
                    AssignOp::Assign => "=",
                    AssignOp::AddAssign => "+=",
                    AssignOp::SubAssign => "-=",
                    AssignOp::MulAssign => "*=",
                    AssignOp::DivAssign => "/=",
                    AssignOp::RemAssign => "%=",
                    AssignOp::BitAndAssign => "&=",
                    AssignOp::BitOrAssign => "|=",
                    AssignOp::BitXorAssign => "^=",
                    AssignOp::ShlAssign => "<<=",
                    AssignOp::ShrAssign => ">>=",
                };
                format!("({} {} {})", target_c, op_str, value_c)
            }
            Expr::Call { callee, args, .. } => {
                let mut arg_strings: Vec<String> =
                    args.iter().map(|a| self.translate_expr(a)).collect();

                // Static method call Class.Method()
                if let Expr::MemberAccess { object, member, .. } = &**callee
                    && let Expr::Ident(class_name, _) = &**object
                    && self.classes.contains_key(class_name)
                {
                    let fn_name = format!("{}_{}", class_name, member);
                    return format!("{}({})", fn_name, arg_strings.join(", "));
                }

                // Member method call obj.Method()
                if let Expr::MemberAccess { object, member, .. } = &**callee {
                    let obj_c = self.translate_expr(object);
                    // Search which class has this method
                    for class in self.classes.values() {
                        for method in &class.methods {
                            if &method.name == member {
                                let fn_name = format!("{}_{}", class.name, member);
                                let ref_arg = format!("&({})", obj_c);
                                arg_strings.insert(0, ref_arg);
                                return format!("{}({})", fn_name, arg_strings.join(", "));
                            }
                        }
                    }
                }

                let callee_c = self.translate_expr(callee);
                format!("{}({})", callee_c, arg_strings.join(", "))
            }
            Expr::Index { array, index, .. } => {
                let arr_c = self.translate_expr(array);
                let idx_c = self.translate_expr(index);
                format!("{}[{}]", arr_c, idx_c)
            }
            Expr::MemberAccess { object, member, .. } => {
                let obj_c = self.translate_expr(object);
                if let Expr::Ident(name, _) = &**object
                    && name == "self"
                {
                    return format!("self->{}", member);
                }
                format!("{}.{}", obj_c, member)
            }
            Expr::ArrayLit { elements, .. } => {
                let elems: Vec<String> = elements.iter().map(|e| self.translate_expr(e)).collect();
                format!("{{{}}}", elems.join(", "))
            }
            Expr::StructLit { name, fields, .. } => {
                let f_strings: Vec<String> = fields
                    .iter()
                    .map(|(k, v)| format!(".{} = {}", k, self.translate_expr(v)))
                    .collect();
                format!("({}){{{}}}", name, f_strings.join(", "))
            }
            Expr::Range { .. } => "0".to_string(),
        }
    }

    fn translate_entry_point(&mut self, program: &Program) {
        let has_main = program.functions.iter().any(|f| f.name == "Main");
        let has_run = program.functions.iter().any(|f| f.name == "Run");
        let has_c_main = program.functions.iter().any(|f| f.name == "main");

        if has_c_main || (!has_main && !has_run) {
            return;
        }

        self.writeln("int main(int argc, char** argv) {");
        self.push_indent();
        self.writeln("(void)argc; (void)argv;");

        if has_main {
            let func = program.functions.iter().find(|f| f.name == "Main").unwrap();
            if func.return_type == Type::Void {
                self.writeln("Main();");
                self.writeln("return 0;");
            } else {
                self.writeln("return (int)Main();");
            }
        } else if has_run {
            let func = program.functions.iter().find(|f| f.name == "Run").unwrap();
            if func.return_type == Type::Void {
                self.writeln("Run();");
                self.writeln("return 0;");
            } else {
                self.writeln("return (int)Run();");
            }
        } else {
            self.writeln("return 0;");
        }

        self.pop_indent();
        self.writeln("}");
    }
}

impl Default for Translator {
    fn default() -> Self {
        Self::new()
    }
}
